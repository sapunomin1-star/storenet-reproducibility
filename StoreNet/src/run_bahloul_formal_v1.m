function provenance = actualSolverProvenance(solver, git)
provenance = struct;
provenance.name = string(func2str(solver));
provenance.interface = "StoreNet MATLAB solver callback";
provenance.version = string(version("-release"));
provenance.matlabVersion = string(version);
provenance.sourceGitCommit = string(git.commit);
optimizationToolbox = ver("optim");
if isempty(optimizationToolbox)
    provenance.optimizationToolboxVersion = "unavailable";
else
    provenance.optimizationToolboxVersion = ...
        string(optimizationToolbox(1).Version);
end
end

function provenance = actualProviderProvenance(provider, git)
provenance = struct;
provenance.name = string(func2str(provider));
provenance.interface = "StoreNet MATLAB data-provider callback";
provenance.matlabVersion = string(version);
provenance.sourceGitCommit = string(git.commit);
end

function provenance = formalCaseProvenance(preflight, referencePath, ...
        solver, provider)
[referenceIds, referenceHashes] = readReferenceInventory(referencePath);
provenance = struct;
provenance.dataContractId = string(preflight.contracts.dataContractId);
provenance.dataContractSha256 = string( ...
    preflight.contracts.dataContractSha256);
provenance.dataContractGitCommit = string( ...
    preflight.contracts.dataContractGitCommit);
provenance.modelContractId = string(preflight.contracts.modelContractId);
provenance.modelContractSha256 = string( ...
    preflight.contracts.modelContractSha256);
provenance.referenceIds = referenceIds;
provenance.referenceHashes = referenceHashes;
provenance.referenceManifestSha256 = string( ...
    preflight.references.manifestSha256);
provenance.solverProvenance = solver;
provenance.dataProviderProvenance = provider;
end

function [ids, hashes] = readReferenceInventory(path)
manifest = readtable(path, Delimiter=",", TextType="string", ...
    VariableNamingRule="preserve");
required = ["ArtifactId", "Sha256"];
missing = required(~ismember(required, ...
    string(manifest.Properties.VariableNames)));
if ~isempty(missing) || height(manifest) == 0
    error("StoreNet:InvalidReferenceManifest", ...
        "Reference manifest lacks ArtifactId/Sha256 inventory rows.");
end
ids = strip(string(manifest.ArtifactId(:)));
hashes = lower(strip(string(manifest.Sha256(:))));
if any(strlength(ids) == 0) || numel(unique(ids)) ~= numel(ids)
    error("StoreNet:InvalidReferenceManifest", ...
        "Reference ArtifactId values must be nonempty and unique.");
end
for hashIndex = 1:numel(hashes)
    validateHex(hashes(hashIndex), 64, ...
        "reference artifact SHA-256");
end
end

function assertNewFormalRoot(path)
if isfolder(path) || isfile(path)
    error("StoreNet:FormalOutputExists", ...
        "Refusing to overwrite existing formal result root: %s", path);
end
end

function hash = sha256File(path)
hash = storenetio.hashFile(path);
end

function root = discoverRepositoryRoot(startFolder)
[status, output] = system("git -C " + shellQuote(startFolder) + ...
    " rev-parse --show-toplevel");
if status ~= 0
    error("StoreNet:RepositoryRootUnavailable", ...
        "Unable to discover the StoreNet repository root.");
end
root = string(strtrim(output));
end

function quoted = shellQuote(value)
quoted = storenetio.shellQuote(value);
end

